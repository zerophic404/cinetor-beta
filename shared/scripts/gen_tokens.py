#!/usr/bin/env python3
"""Emit platform token files from shared/tokens/*.json.

Outputs (shared/generated/):
  Tokens.kt   - Kotlin (package com.mythbrix.cinetor.design), Compose Color/Dp
  tokens.css  - CSS custom properties (:root = default theme, [data-theme=...])
  tokens.ts   - typed TypeScript export

Usage: python3 shared/scripts/gen_tokens.py [--out DIR]
"""
import argparse
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # shared/
TOK = os.path.join(ROOT, "tokens")
HEX_RE = re.compile(r"^#([0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?$")


def load(name):
    with open(os.path.join(TOK, name), encoding="utf-8") as f:
        return json.load(f)


def kt_color(hexstr):
    """'#RRGGBB[AA]' -> 'Color(0xAARRGGBBL)'."""
    m = HEX_RE.match(hexstr)
    if not m:
        raise ValueError(f"bad color {hexstr!r}")
    rgb = m.group(1).upper()
    aa = (m.group(2) or "FF").upper()
    return f"Color(0x{aa}{rgb}L)"


def kebab(s):
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), s)


def fnum(x):
    s = repr(float(x))
    return s + "f"


def gen_kotlin(themes, motion, shape):
    order = list(themes["themes"].keys())
    color_keys = list(themes["themes"][order[0]]["colors"].keys())
    L = []
    w = L.append
    w("// GENERATED by shared/scripts/gen_tokens.py — DO NOT EDIT.")
    w('@file:Suppress("MagicNumber", "unused")')
    w("")
    w("package com.mythbrix.cinetor.design")
    w("")
    w("import androidx.compose.animation.core.CubicBezierEasing")
    w("import androidx.compose.ui.graphics.Color")
    w("import androidx.compose.ui.unit.Dp")
    w("import androidx.compose.ui.unit.dp")
    w("")
    w("enum class AppTheme { " + ", ".join(t.upper() for t in order) + " }")
    w("")
    w("interface CinetorThemeTokens {")
    w("    val name: String")
    w("    val isLight: Boolean")
    for k in color_keys:
        w(f"    val {k}: Color")
    w("    val blur: Dp")
    w("    val tintStrength: Float")
    w("}")
    w("")
    w("object CinetorTokens {")
    w(f"    val Default: AppTheme = AppTheme.{themes['default'].upper()}")
    w("")
    for t in order:
        th = themes["themes"][t]
        is_light = "true" if th["isLight"] else "false"
        w(f"    object {th['name']} : CinetorThemeTokens {{")
        w(f"        override val name: String = \"{th['name']}\"")
        w(f"        override val isLight: Boolean = {is_light}")
        for k in color_keys:
            w(f"        override val {k}: Color = {kt_color(th['colors'][k])}")
        w(f"        override val blur: Dp = {int(th['blurDp'])}.dp")
        w(f"        override val tintStrength: Float = {fnum(th['tintStrength'])}")
        w("    }")
        w("")
    w("    fun of(theme: AppTheme): CinetorThemeTokens = when (theme) {")
    for t in order:
        w(f"        AppTheme.{t.upper()} -> {themes['themes'][t]['name']}")
    w("    }")
    w("")
    d = motion["durationsMs"]
    w("    object Motion {")
    for k, v in d.items():
        w(f"        const val {k}Ms: Int = {int(v)}")
    for k, v in motion["easing"].items():
        a = ", ".join(fnum(x) for x in v)
        w(f"        val {k}: CubicBezierEasing = CubicBezierEasing({a})")
    w(f"        const val springStiffness: Float = {fnum(motion['spring']['stiffness'])}")
    w(f"        const val springDampingRatio: Float = {fnum(motion['spring']['dampingRatio'])}")
    w(f"        const val heroAutoAdvanceMs: Long = {int(motion['heroAutoAdvanceMs'])}L")
    w(f"        const val tintAnimMs: Int = {int(motion['tintAnimMs'])}")
    w(f"        const val lowTierDurationScale: Float = {fnum(motion['lowTierDurationScale'])}")
    for k, v in motion["crossfadeMs"].items():
        w(f"        const val crossfade{k.capitalize()}Ms: Int = {int(v)}")
    w(f"        const val cardFocusScale: Float = {fnum(motion['cardFocusScale'])}")
    w("    }")
    w("")
    w("    object Shape {")
    for k, v in shape["radiiDp"].items():
        w(f"        val {k}: Dp = {int(v)}.dp")
    w(f"        const val tileRadiusRatio: Float = {fnum(shape['tileRadiusRatio'])}")
    for k, v in shape["strokeDp"].items():
        w(f"        val stroke{k.capitalize()}: Dp = {int(v)}.dp")
    w("    }")
    w("")
    w("    object Spacing {")
    for k, v in shape["spacingDp"].items():
        w(f"        val {k}: Dp = {int(v)}.dp")
    w("    }")
    w("}")
    return "\n".join(L) + "\n"


def gen_css(themes, motion, shape):
    order = list(themes["themes"].keys())
    L = ["/* GENERATED by shared/scripts/gen_tokens.py — DO NOT EDIT. */", ""]
    w = L.append

    def theme_block(selector, th):
        scheme = "light" if th["isLight"] else "dark"
        w(f"{selector} {{")
        w(f"  color-scheme: {scheme};")
        for k, v in th["colors"].items():
            w(f"  --{kebab(k)}: {v};")
        w(f"  --blur: {int(th['blurDp'])}px;")
        w(f"  --tint-strength: {th['tintStrength']};")
        w("}")
        w("")

    # shared non-theme tokens + default theme in :root
    w(":root {")
    for k, v in motion["durationsMs"].items():
        w(f"  --dur-{k}: {int(v)}ms;")
    for k, v in motion["easing"].items():
        w(f"  --ease-{k}: cubic-bezier({', '.join(str(x) for x in v)});")
    w(f"  --hero-auto-advance: {int(motion['heroAutoAdvanceMs'])}ms;")
    w(f"  --tint-anim: {int(motion['tintAnimMs'])}ms;")
    w(f"  --low-tier-duration-scale: {motion['lowTierDurationScale']};")
    w(f"  --card-focus-scale: {motion['cardFocusScale']};")
    for k, v in shape["radiiDp"].items():
        w(f"  --radius-{k}: {int(v)}px;")
    w(f"  --tile-radius-ratio: {shape['tileRadiusRatio']};")
    for k, v in shape["spacingDp"].items():
        w(f"  --space-{int(v)}: {int(v)}px;")
    w("}")
    w("")
    theme_block(":root", themes["themes"][themes["default"]])
    for t in order:
        theme_block(f'[data-theme="{t}"]', themes["themes"][t])
    light_selectors = ", ".join(f':root[data-theme="{t}"]' for t in order if themes["themes"][t]["isLight"])
    if light_selectors:
        w(f"{light_selectors} {{ color-scheme: light; }}")
    w(":root, [data-theme] { --accent-gradient: linear-gradient(90deg, var(--accent), var(--accent-end)); }")
    return "\n".join(L) + "\n"


def gen_ts(themes, motion, shape):
    order = list(themes["themes"].keys())
    color_keys = list(themes["themes"][order[0]]["colors"].keys())
    L = ["// GENERATED by shared/scripts/gen_tokens.py — DO NOT EDIT.", ""]
    w = L.append
    w("export type ThemeName = " + " | ".join(f"'{t}'" for t in order) + ";")
    w("")
    w("export interface ThemeTokens {")
    w("  name: string;")
    w("  isLight: boolean;")
    w("  colors: {")
    for k in color_keys:
        w(f"    {k}: string;")
    w("  };")
    w("  blurDp: number;")
    w("  tintStrength: number;")
    w("}")
    w("")
    w(f"export const defaultTheme: ThemeName = '{themes['default']}';")
    w("")
    slim = {
        t: {
            "name": th["name"],
            "isLight": bool(th["isLight"]),
            "colors": th["colors"],
            "blurDp": th["blurDp"],
            "tintStrength": th["tintStrength"],
        }
        for t, th in themes["themes"].items()
    }
    w("export const themes: Record<ThemeName, ThemeTokens> = " + json.dumps(slim, indent=2) + ";")
    w("")
    w("export const motion = " + json.dumps(motion, indent=2) + " as const;")
    w("")
    w("export const shape = " + json.dumps(shape, indent=2) + " as const;")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "generated"))
    a = ap.parse_args()
    themes, motion, shape = load("themes.json"), load("motion.json"), load("shape.json")
    if themes["default"] not in themes["themes"]:
        raise SystemExit(f"unknown default theme {themes['default']!r}")
    expected_keys = list(next(iter(themes["themes"].values()))["colors"].keys())
    for t, th in themes["themes"].items():
        if not isinstance(th.get("isLight"), bool):
            raise SystemExit(f"{t}.isLight: expected bool, got {th.get('isLight')!r}")
        if list(th["colors"].keys()) != expected_keys:
            raise SystemExit(f"{t}.colors: keys mismatch")
        for k, v in th["colors"].items():
            if not HEX_RE.match(v):
                raise SystemExit(f"{t}.{k}: bad color {v}")
    os.makedirs(a.out, exist_ok=True)
    outs = {
        "Tokens.kt": gen_kotlin(themes, motion, shape),
        "tokens.css": gen_css(themes, motion, shape),
        "tokens.ts": gen_ts(themes, motion, shape),
    }
    for name, body in outs.items():
        p = os.path.join(a.out, name)
        with open(p, "w", encoding="utf-8") as f:
            f.write(body)
        print("wrote", p)


if __name__ == "__main__":
    main()
